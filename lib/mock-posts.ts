export function getPostBySlug(slug: string): Post | undefined {
  return mockPosts.find(post => post.slug === slug)
}

export function getFeaturedPost(): Post | undefined {
  return mockPosts.find(post => post.featured)
}

export function getPostsByCategory(category: string): Post[] {
  return mockPosts.filter(post => post.category === category)
}

export function getRelatedPosts(currentSlug: string, limit: number = 3): Post[] {
  const currentPost = getPostBySlug(currentSlug)
  if (!currentPost) return mockPosts.slice(0, limit)
  
  return mockPosts
    .filter(post => post.slug !== currentSlug && post.category === currentPost.category)
    .slice(0, limit)
    .concat(
      mockPosts
        .filter(post => post.slug !== currentSlug && post.category !== currentPost.category)
        .slice(0, limit)
    )
    .slice(0, limit)
}
